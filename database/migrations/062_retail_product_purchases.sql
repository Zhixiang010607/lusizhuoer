CREATE OR REPLACE FUNCTION public.review_retail_product_purchase(
  p_record_id BIGINT, p_reviewer_account_id BIGINT, p_decision TEXT, p_note TEXT
)
RETURNS TABLE(record_id BIGINT, purchase_code TEXT, record_status TEXT, reviewed_at TIMESTAMPTZ)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE reviewer public.staff_accounts%ROWTYPE;
BEGIN
  SELECT * INTO reviewer FROM public.staff_accounts WHERE id = p_reviewer_account_id FOR KEY SHARE;
  IF NOT FOUND OR reviewer.role_code <> 'hq' OR reviewer.account_status <> 'ACTIVE' THEN
    RAISE EXCEPTION 'RETAIL_PRODUCT_PURCHASE_REVIEWER_FORBIDDEN';
  END IF;
  IF UPPER(BTRIM(COALESCE(p_decision, ''))) NOT IN ('APPROVED', 'REJECTED') THEN
    RAISE EXCEPTION 'RETAIL_PRODUCT_PURCHASE_DECISION_INVALID';
  END IF;
  RETURN QUERY
  UPDATE public.retail_product_purchase_records purchase
     SET record_status = UPPER(BTRIM(p_decision)),
         reviewed_by_account_id = reviewer.id,
         review_note = LEFT(COALESCE(p_note, ''), 1000),
         reviewed_at = NOW(), updated_at = NOW()
   WHERE purchase.id = p_record_id AND purchase.record_status = 'PENDING'
  RETURNING purchase.id, purchase.purchase_code, purchase.record_status, purchase.reviewed_at;
  IF NOT FOUND THEN RAISE EXCEPTION 'RETAIL_PRODUCT_PURCHASE_NOT_PENDING'; END IF;
END;
$$;

REVOKE ALL ON FUNCTION public.review_retail_product_purchase(BIGINT, BIGINT, TEXT, TEXT) FROM PUBLIC;
ALTER TABLE public.retail_product_purchase_records ENABLE ROW LEVEL SECURITY;

COMMENT ON TABLE public.retail_product_purchase_records IS
  'Independent physical/retail product purchase applications submitted by store or teacher accounts and reviewed by headquarters.';

COMMIT;
