DROP TRIGGER IF EXISTS trg_062_prevent_retail_product_purchase_delete ON public.retail_product_purchase_records;
CREATE TRIGGER trg_062_prevent_retail_product_purchase_delete
BEFORE DELETE ON public.retail_product_purchase_records
