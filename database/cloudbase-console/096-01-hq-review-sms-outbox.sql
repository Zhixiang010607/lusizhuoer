-- Requires 094 and 095. Run only through cloudbase-pg-change.js backup gate.
-- Installs the sender DISABLED. No historical backfill and no preference changes.
BEGIN;
CREATE TABLE public.hq_review_sms_delivery_state (
  singleton boolean PRIMARY KEY DEFAULT true CHECK(singleton),
  enabled boolean NOT NULL DEFAULT false,
  sdk_app_id text NOT NULL DEFAULT '1401179904' CHECK(sdk_app_id ~ '^140[0-9]{7}$'),
  activated_at timestamptz,
  CHECK(NOT enabled OR activated_at IS NOT NULL)
);
INSERT INTO public.hq_review_sms_delivery_state(singleton) VALUES(true);

CREATE TABLE public.hq_review_sms_outbox (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category text NOT NULL CHECK(category IN ('purchase','recharge','refund','verification')),
  source_record_id bigint NOT NULL,
  recipient_account_id bigint NOT NULL,
  phone_snapshot text NOT NULL CHECK(phone_snapshot ~ '^\+861[3-9][0-9]{9}$'),
  status text NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','CLAIMED','SENDING','ACCEPTED','REJECTED','UNKNOWN','CANCELLED')),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  lease_token text,
  lease_until timestamptz,
  attempt_count integer NOT NULL DEFAULT 0 CHECK(attempt_count BETWEEN 0 AND 1),
  provider_code text,
  provider_request_id text,
  provider_serial_no text,
  UNIQUE(category,source_record_id,recipient_account_id)
);
CREATE INDEX hq_review_sms_pending_idx ON public.hq_review_sms_outbox(id) WHERE status IN ('PENDING','CLAIMED','SENDING');
ALTER TABLE public.hq_review_sms_delivery_state ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.hq_review_sms_outbox ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.hq_review_sms_delivery_state, public.hq_review_sms_outbox FROM PUBLIC,anon,authenticated;
REVOKE ALL ON SEQUENCE public.hq_review_sms_outbox_id_seq FROM PUBLIC,anon,authenticated;
GRANT SELECT ON public.hq_review_sms_delivery_state TO service_role;
-- Worker transitions only through the narrowly scoped functions below.

CREATE FUNCTION public.hq_review_sms_phone_v96(p_phone text) RETURNS text
LANGUAGE sql IMMUTABLE SET search_path=public,pg_temp AS $$
  SELECT CASE WHEN btrim(p_phone) ~ '^1[3-9][0-9]{9}$' THEN '+86'||btrim(p_phone)
              WHEN btrim(p_phone) ~ '^\+861[3-9][0-9]{9}$' THEN btrim(p_phone) END;
$$;

CREATE FUNCTION public.enqueue_hq_review_sms_v96() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE kind text; activation timestamptz;
BEGIN
  SELECT activated_at INTO activation FROM public.hq_review_sms_delivery_state WHERE singleton AND enabled;
  IF activation IS NULL OR NEW.submitted_at < activation OR NEW.record_status <> 'PENDING' THEN RETURN NEW; END IF;
  IF TG_TABLE_NAME='retail_product_purchase_records' THEN kind:='purchase';
  ELSIF TG_TABLE_NAME='recharge_records' THEN
    IF NEW.recharge_type='NEW' THEN kind:='recharge'; ELSIF NEW.recharge_type='REFUND' THEN kind:='refund'; END IF;
  ELSIF TG_TABLE_NAME='verification_records' AND NEW.verification_type='SUPPLEMENT' AND NEW.void_request_status='NONE' THEN kind:='verification';
  END IF;
  IF kind IS NULL THEN RETURN NEW; END IF;
  INSERT INTO public.hq_review_sms_outbox(category,source_record_id,recipient_account_id,phone_snapshot)
    SELECT kind,NEW.id,a.id,public.hq_review_sms_phone_v96(a.phone)
    FROM public.staff_accounts a JOIN public.hq_review_sms_preferences p ON p.staff_account_id=a.id
    WHERE a.role_code='hq' AND a.account_status='ACTIVE' AND p.enabled
      AND CASE kind WHEN 'purchase' THEN p.purchase WHEN 'recharge' THEN p.recharge WHEN 'refund' THEN p.refund ELSE p.verification END
      AND public.hq_review_sms_phone_v96(a.phone) IS NOT NULL
    ON CONFLICT(category,source_record_id,recipient_account_id) DO NOTHING;
  RETURN NEW;
END;
$$;
CREATE TRIGGER enqueue_purchase_review_sms AFTER INSERT ON public.retail_product_purchase_records FOR EACH ROW EXECUTE FUNCTION public.enqueue_hq_review_sms_v96();
CREATE TRIGGER enqueue_recharge_review_sms AFTER INSERT ON public.recharge_records FOR EACH ROW EXECUTE FUNCTION public.enqueue_hq_review_sms_v96();
CREATE TRIGGER enqueue_verification_review_sms AFTER INSERT ON public.verification_records FOR EACH ROW EXECUTE FUNCTION public.enqueue_hq_review_sms_v96();

CREATE FUNCTION public.hq_review_sms_eligible_v96(p_id bigint) RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public,pg_temp AS $$
 SELECT EXISTS(SELECT 1 FROM public.hq_review_sms_outbox q
  JOIN public.hq_review_sms_delivery_state d ON d.singleton AND d.enabled AND q.created_at>=d.activated_at
  JOIN public.staff_accounts a ON a.id=q.recipient_account_id AND a.role_code='hq' AND a.account_status='ACTIVE'
  JOIN public.hq_review_sms_preferences p ON p.staff_account_id=a.id AND p.enabled
  WHERE q.id=p_id AND q.created_at>clock_timestamp()-interval '24 hours'
   AND public.hq_review_sms_phone_v96(a.phone)=q.phone_snapshot
   AND CASE q.category WHEN 'purchase' THEN p.purchase WHEN 'recharge' THEN p.recharge WHEN 'refund' THEN p.refund ELSE p.verification END
   AND CASE q.category
    WHEN 'purchase' THEN EXISTS(SELECT 1 FROM public.retail_product_purchase_records r WHERE r.id=q.source_record_id AND r.record_status='PENDING')
    WHEN 'recharge' THEN EXISTS(SELECT 1 FROM public.recharge_records r WHERE r.id=q.source_record_id AND r.record_status='PENDING' AND r.recharge_type='NEW')
    WHEN 'refund' THEN EXISTS(SELECT 1 FROM public.recharge_records r WHERE r.id=q.source_record_id AND r.record_status='PENDING' AND r.recharge_type='REFUND')
    ELSE EXISTS(SELECT 1 FROM public.verification_records r WHERE r.id=q.source_record_id AND r.record_status='PENDING' AND r.verification_type='SUPPLEMENT' AND r.void_request_status='NONE') END);
$$;

CREATE FUNCTION public.claim_hq_review_sms_v96(p_token text) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE job public.hq_review_sms_outbox%ROWTYPE;
BEGIN
  IF p_token !~ '^[a-f0-9]{32}$' OR p_token IS NULL THEN RAISE EXCEPTION 'SMS_INVALID_LEASE'; END IF;
  -- A crashed sender may already have delivered. Never automatically resend it.
  UPDATE public.hq_review_sms_outbox SET status='UNKNOWN',updated_at=clock_timestamp(),provider_code='SENDER_INTERRUPTED'
   WHERE status='SENDING' AND lease_until<clock_timestamp();
  UPDATE public.hq_review_sms_outbox SET status='PENDING',lease_token=NULL,lease_until=NULL,updated_at=clock_timestamp()
   WHERE status='CLAIMED' AND lease_until<clock_timestamp() AND attempt_count=0;
  -- Bound each call, even if many accounts have opted out or jobs have expired.
  SELECT * INTO job FROM public.hq_review_sms_outbox WHERE status='PENDING' ORDER BY id FOR UPDATE SKIP LOCKED LIMIT 1;
  IF NOT FOUND THEN RETURN NULL; END IF;
  IF NOT public.hq_review_sms_eligible_v96(job.id) THEN
    UPDATE public.hq_review_sms_outbox SET status='CANCELLED',updated_at=clock_timestamp() WHERE id=job.id;
    RETURN jsonb_build_object('skipped',true);
  END IF;
  UPDATE public.hq_review_sms_outbox SET status='CLAIMED',lease_token=p_token,lease_until=clock_timestamp()+interval '2 minutes',updated_at=clock_timestamp() WHERE id=job.id;
  RETURN jsonb_build_object('id',job.id::text,'category',job.category,'phone',job.phone_snapshot);
END;
$$;

CREATE FUNCTION public.start_hq_review_sms_v96(p_id bigint,p_token text) RETURNS boolean
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
BEGIN
  PERFORM id FROM public.hq_review_sms_outbox WHERE id=p_id AND status='CLAIMED' AND lease_token=p_token AND lease_until>clock_timestamp() AND attempt_count=0 FOR UPDATE;
  IF NOT FOUND THEN RETURN false; END IF;
  IF NOT public.hq_review_sms_eligible_v96(p_id) THEN
    UPDATE public.hq_review_sms_outbox SET status='CANCELLED',updated_at=clock_timestamp() WHERE id=p_id;
    RETURN false;
  END IF;
  UPDATE public.hq_review_sms_outbox SET status='SENDING',attempt_count=1,updated_at=clock_timestamp() WHERE id=p_id;
  RETURN true;
END;
$$;

CREATE FUNCTION public.finish_hq_review_sms_v96(p_id bigint,p_token text,p_status text,p_code text,p_request text,p_serial text) RETURNS boolean
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
BEGIN
  IF p_status NOT IN ('ACCEPTED','REJECTED','UNKNOWN') OR p_status IS NULL THEN RAISE EXCEPTION 'SMS_INVALID_RESULT'; END IF;
  IF p_status='ACCEPTED' AND (p_code IS DISTINCT FROM 'Ok' OR coalesce(p_serial,'')='') THEN RAISE EXCEPTION 'SMS_UNCONFIRMED_ACCEPTANCE'; END IF;
  UPDATE public.hq_review_sms_outbox SET status=p_status,provider_code=left(p_code,100),provider_request_id=left(p_request,100),provider_serial_no=left(p_serial,200),updated_at=clock_timestamp()
    WHERE id=p_id AND lease_token=p_token AND status='SENDING' AND attempt_count=1;
  RETURN FOUND;
END;
$$;

REVOKE ALL ON FUNCTION public.hq_review_sms_phone_v96(text),public.enqueue_hq_review_sms_v96(),public.hq_review_sms_eligible_v96(bigint),public.claim_hq_review_sms_v96(text),public.start_hq_review_sms_v96(bigint,text),public.finish_hq_review_sms_v96(bigint,text,text,text,text,text) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.claim_hq_review_sms_v96(text),public.start_hq_review_sms_v96(bigint,text),public.finish_hq_review_sms_v96(bigint,text,text,text,text,text) TO service_role;
COMMIT;
